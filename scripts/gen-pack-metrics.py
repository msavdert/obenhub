"""Generate docs/reference/<pack>-pack-metrics.md from each pack query file.

gen-pack-metrics.py           write the page
gen-pack-metrics.py --check   fail when the page on disk differs from what would be written
"""

import sys
from pathlib import Path

from packmetrics import parse_metrics

ROOT = Path(__file__).resolve().parent.parent
# (pack directory under lab/packs, page title)
PACKS = (("postgresql", "PostgreSQL pack metrics"), ("oracledb-dg", "Oracle Data Guard pack metrics"))


def cell(text):
    return text.replace("|", "\\|")


def render(pack, title):
    source = ROOT / "lab/packs" / pack / "queries.yaml"
    metrics, mentions = parse_metrics(source)
    if mentions != len(metrics):
        sys.exit(f"{source}: {mentions} metric_name lines, {len(metrics)} parsed")
    rows = ["| Name | Type | Unit | Attributes | Description |", "| --- | --- | --- | --- | --- |"]
    for m in sorted(metrics, key=lambda m: m["metric_name"]):
        kind = "gauge" if m["data_type"] == "gauge" else "sum, monotonic" if m.get("monotonic") == "true" else "sum"
        attrs = ", ".join(f"`{a}`" for a in m.get("attribute_columns", [])) or "-"
        rows.append(
            f"| `{m['metric_name']}` | {kind} | `{m.get('unit', '')}` | {attrs} | {cell(m.get('description', ''))} |"
        )
    return (
        f"# {title}\n\n"
        f"Generated by `scripts/gen-pack-metrics.py` from `lab/packs/{pack}/queries.yaml`; do not edit.\n\n"
        + "\n".join(rows)
        + "\n"
    )


def main():
    stale = 0
    for pack, title in PACKS:
        text = render(pack, title)
        target = ROOT / "docs/reference" / f"{pack}-pack-metrics.md"
        if "--check" in sys.argv:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                print(f"{target.relative_to(ROOT)} is stale: run scripts/gen-pack-metrics.py", file=sys.stderr)
                stale = 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return stale


if __name__ == "__main__":
    sys.exit(main())
