"""Generate docs/reference/<pack>-pack-alerts.md from each packs/<pack>/rules.yml.

gen-pack-alerts.py           write the pages
gen-pack-alerts.py --check   fail when a page on disk differs from what would be written

Every alert is a `##` heading named as the alert, so its anchor is the
lowercased name (the toc extension's id; `#postgrestargetabsent`). That anchor
is what the `runbook_url` annotation of an alert no scenario fires points to
(scripts/check-alert-docs.py). An alert with two severities is one section
with one entry per tier.
"""

import sys

from packalerts import ROOT, pack_alerts

TITLES = {
    "cnpg": "CloudNativePG pack alerts",
    "collector": "Collector pack alerts",
    "etcd": "etcd pack alerts",
    "host": "Host pack alerts",
    "k8s": "Kubernetes pack alerts",
    "oracledb-backup": "Oracle RMAN backup pack alerts",
    "oracledb-dg": "Oracle Data Guard pack alerts",
    "patroni": "Patroni pack alerts",
    "pgbackrest": "pgBackRest pack alerts",
    "pgbouncer": "PgBouncer pack alerts",
    "postgresql": "PostgreSQL pack alerts",
}


def render(pack, alerts):
    out = [
        f"# {TITLES[pack]}\n",
        f"Generated by `scripts/gen-pack-alerts.py` from `packs/{pack}/rules.yml`; do not edit. "
        "Each alert is a heading named as the alert, so its anchor is the lowercased name. "
        "An alert with two severities has one entry per tier.\n",
    ]
    names = []
    for a in alerts:
        if a["name"] not in names:
            names.append(a["name"])
    for name in names:
        tiers = [a for a in alerts if a["name"] == name]
        out.append(f"## {name}\n")
        out.append(tiers[0]["annotations"]["description"] + "\n")
        for t in tiers:
            hold = f"for {t['for']}" if t["for"] else "no hold time"
            out.append(f"**{t['severity']}**, {hold}\n")
            out.append("```text\n" + t["expr"] + "\n```\n")
    return "\n".join(out)


def main():
    stale = 0
    for pack, alerts in pack_alerts().items():
        text = render(pack, alerts)
        target = ROOT / "docs/reference" / f"{pack}-pack-alerts.md"
        if "--check" in sys.argv:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                print(f"{target.relative_to(ROOT)} is stale: run scripts/gen-pack-alerts.py", file=sys.stderr)
                stale = 1
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return stale


if __name__ == "__main__":
    sys.exit(main())
