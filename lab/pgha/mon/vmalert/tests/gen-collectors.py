#!/usr/bin/env python3
"""Generate collectors.yml, the vmalert unit tests for Collector liveness in
the pgha lab (inventory: ../inventory.yml; rules: lab/packs/*/rules.yml).

Every case seeds the same series for the gateway and the three nodes
(self-metrics, PostgreSQL heartbeat, Patroni and etcd `up`) and varies which
Collector stops and which scrape fails; the expected alert sets are written out
per evaluation time.

Usage, standard library only:
    python3 lab/pgha/mon/vmalert/tests/gen-collectors.py > lab/pgha/mon/vmalert/tests/collectors.yml
    python3 lab/pgha/mon/vmalert/tests/gen-collectors.py PATH   # write to PATH
`mise run lab:pgha:rules-gen-check` fails when the committed YAML differs.
"""
import sys

SAMPLES = 60          # 15 s apart: 15 minutes of input
STOP_AT = 8           # a stopped Collector's last self-metric is sample 8 (2 m)
# Judged every 30 s from 2m30s to 7m: the window in which a gate wider than 1 m
# would let a target alert fire.
TIMES = [150 + 30 * i for i in range(10)]
SCENARIO_SAMPLES = 120    # 30 minutes
# CollectorAbsent: the 2 m window empties at 3m45s and the alert fires after
# for: 1m (4m45s), so it is asserted from 5m on (300 s).
FIRING_FROM = 300

HEADER = """\
# Generated by gen-collectors.py in this directory; edit the generator, not this file.
# Collector liveness in the pgha lab: three node Collectors that send through
# the gateway Collector (inventory: lab/pgha/mon/vmalert/inventory.yml), and the
# shared pack rules reading it. Each node's PostgreSQL heartbeat, Patroni and
# etcd scrapes are collected by that node's Collector, so they stop with it; when
# the gateway stops, every node's data and self-metrics stop together. Samples
# are 15 s apart; self-metrics stop after 2 m (8 samples). The timing tests are
# judged every 30 s from 2m30s to 7m, the window in which a gate wider than 1 m
# would let a target alert fire; the data of a stopped Collector may outlive its
# last self-metric by 15 to 30 s (the last batch can arrive late).
# CollectorAbsent: the 2 m window empties at 3m45s, firing after for: 1m (4m45s).
rule_files:
{rule_files}
evaluation_interval: 15s

tests:
"""
RULE_FILES = [
    "../inventory.yml",
    "../../../../packs/postgresql/rules.yml",
    "../../../../packs/patroni/rules.yml",
    "../../../../packs/etcd/rules.yml",
]

# alertname -> rule group
GROUPS = {
    "CollectorAbsent": "postgresql",
    "PostgresTargetAbsent": "postgresql",
    "PatroniTargetAbsent": "patroni",
    "EtcdMemberAbsent": "etcd",
    "EtcdInsufficientMembers": "etcd",
    "PatroniNoWritablePrimary": "patroni",
}


def fmt(seconds):
    minutes, rest = divmod(seconds, 60)
    return f"{minutes}m" + (f"{rest}s" if rest else "")


def input_series(
    coll_stop=(),
    gw_stop=False,
    hb_stop=(),
    etcd_fail=(),
    patroni_fail=(),
    lag=0,
    leader=None,
    samples=SAMPLES,
):
    """The input_series block. A stopped Collector's self-metric stops after
    STOP_AT samples; what it collected stops `lag` samples later (the last
    batch can arrive after the last self-metric). A failing scrape reads 0.
    patroni_primary is 1 on `leader` and 0 on the other nodes; leader=0 means
    no member reports primary; by default the leader is the first node whose
    Collector and Patroni scrape both work. Its series ends with the node's
    data."""
    out = []

    def add(selector, values):
        out.append(f"      - series: '{selector}'\n        values: '{values}'")

    def stream(value, until=None):
        if until is None:
            return f"{value}x{samples}"
        return f"{value}x{until} _x{samples - until}"

    def failing():
        return f"1x{STOP_AT} 0x{samples - STOP_AT}"

    if leader is None:
        working = [i for i in (1, 2, 3) if i not in coll_stop and i not in patroni_fail]
        leader = working[0] if working else 1
    uptime = 'otelcol_process_uptime{service.name="otelcol",service.instance.id="otelcol-%s"}'
    add(uptime % "gateway", stream(1, STOP_AT if gw_stop else None))
    for i in (1, 2, 3):
        node = f"pgha-{i}"
        dead = gw_stop or i in coll_stop
        data = STOP_AT + lag if dead else None
        add(uptime % node, stream(1, STOP_AT if dead else None))
        heartbeat = STOP_AT if (i in hb_stop and not dead) else data
        add(f'postgresql.collection.heartbeat{{service.name="postgresql",service.instance.id="{node}"}}',
            stream(1, heartbeat))
        for service, fails in (("patroni", patroni_fail), ("etcd", etcd_fail)):
            values = failing() if (i in fails and not dead) else stream(1, data)
            add(f'up{{service.name="{service}",service.instance.id="{node}"}}', values)
        primary = data if i not in patroni_fail else STOP_AT
        add(f'patroni_primary{{service.name="patroni",scope="pgha",service.instance.id="{node}"}}',
            stream(1 if i == leader else 0, primary))
    return "\n".join(out)


def alert(labels, summary):
    """One exp_alerts entry; labels is a list of (key, value)."""
    lines = ["- exp_labels:"]
    lines += [f"    {key}: {value}" for key, value in labels]
    lines += ["  exp_annotations:", f"    summary: {summary}"]
    return "\n".join(" " * 10 + line for line in lines)


def collector_alert(name):
    labels = [
        ("severity", "critical"),
        ("service.namespace", "obenhub-lab"),
        ("service.instance.id", f"otelcol-{name}"),
    ]
    if name != "gateway":
        labels.append(("obenhub.upstream", "otelcol-gateway"))
    return alert(labels, f"Collector otelcol-{name} reports no self-metrics")


def inventory_alert(severity, service, node, summary):
    labels = [
        ("severity", severity),
        ("service.namespace", "obenhub-lab"),
        ("service.name", service),
    ]
    if service != "etcd":
        labels.append(("db.cluster.name", "pgha"))
    labels += [
        ("service.instance.id", f"pgha-{node}"),
        ("obenhub.collector", f"otelcol-pgha-{node}"),
    ]
    return alert(labels, summary)


def postgres_absent(node):
    summary = f"No heartbeat from pgha-{node}"
    return inventory_alert("critical", "postgresql", node, summary)


def patroni_absent(node):
    return inventory_alert(
        "critical", "patroni", node,
        f"Patroni on pgha-{node} is not scraped while PostgreSQL still reports")


def etcd_absent(node):
    summary = f"etcd member pgha-{node} is not scraped"
    return inventory_alert("warning", "etcd", node, summary)


def insufficient(reporting):
    summary = f'"Only {reporting} etcd members report: quorum is lost"'
    lines = [
        "- exp_labels: {severity: critical}",
        "  exp_annotations:",
        f"    summary: {summary}",
    ]
    return "\n".join(" " * 10 + line for line in lines)


def no_primary():
    lines = [
        "- exp_labels: {severity: critical, scope: pgha}",
        "  exp_annotations:",
        "    summary: Cluster pgha has no writable primary",
    ]
    return "\n".join(" " * 10 + line for line in lines)


def render(times, expected_at):
    """eval_time entries for all six alert names; expected_at(t) maps
    alertname -> list of alert entries (missing or empty: none)."""
    checks = ""
    for t in times:
        expected = expected_at(t)
        for alertname, group in GROUPS.items():
            entries = expected.get(alertname)
            checks += f"      - eval_time: {fmt(t)}\n"
            checks += f"        groupname: {group}\n"
            checks += f"        alertname: {alertname}\n"
            if entries:
                checks += "        exp_alerts:\n" + "\n".join(entries) + "\n"
            else:
                checks += "        exp_alerts: []\n"
    return checks


def test_block(name, series_block, checks):
    return (f'  - name: "{name}"\n    interval: 15s\n    input_series:\n'
            f"{series_block}\n    alert_rule_test:\n{checks}\n")


def case(name, series_block, expected, times=TIMES):
    """One test. expected maps alertname -> list of alert entries that must be
    firing from FIRING_FROM on; before that, and for every other alert, the
    expectation is an empty list."""
    checks = render(times, lambda t: expected if t >= FIRING_FROM else {})
    return test_block(name, series_block, checks)


def segments(parts):
    """[(value, samples), ...] -> a values string; value "_" is a gap."""
    return " ".join(f"{value}x{count}" for value, count in parts)


def scenario_series(nodes):
    """input_series for the 30-minute scenarios, written per node as segment
    lists: prim (patroni_primary), col (Collector self-metrics; also the
    default for the heartbeat, the Patroni `up` and the etcd `up`), hb and
    pat (override the heartbeat and the Patroni `up`). The gateway stays up."""
    out = []

    def add(selector, parts):
        out.append(f"      - series: '{selector}'\n        values: '{segments(parts)}'")

    add('otelcol_process_uptime{service.name="otelcol",service.instance.id="otelcol-gateway"}',
        [(1, SCENARIO_SAMPLES)])
    for i, node in nodes.items():
        col = node["col"]
        add(f'otelcol_process_uptime{{service.name="otelcol",service.instance.id="otelcol-pgha-{i}"}}', col)
        add(f'postgresql.collection.heartbeat{{service.name="postgresql",service.instance.id="pgha-{i}"}}',
            node.get("hb", col))
        add(f'up{{service.name="patroni",service.instance.id="pgha-{i}"}}', node.get("pat", col))
        add(f'up{{service.name="etcd",service.instance.id="pgha-{i}"}}', col)
        add(f'patroni_primary{{service.name="patroni",scope="pgha",service.instance.id="pgha-{i}"}}',
            node["prim"])
    return "\n".join(out)


def scenario(name, nodes, phases):
    """phases: [(times, expected), ...]; expected is the exact alert set at
    every one of those times."""
    checks = ""
    for times, expected in phases:
        checks += render(times, lambda t, e=expected: e)
    return test_block(name, scenario_series(nodes), checks)


def scenarios(c1, c2):
    """Who was the primary when a Collector died. Sample k is at 15k seconds.
    The first scenario of build() (the leader's Collector stops) is the case
    where nobody is promoted. A stale patroni_primary reads as sum 0 after the
    5 m lookback, so alerts are asserted from 15m on (900 s) unless noted."""
    alive = [(1, SCENARIO_SAMPLES)]
    n = SCENARIO_SAMPLES
    zeros = [(0, n)]
    late = [900, 1200, 1500, 1800]
    out = ""
    # S5: the leader's Patroni dies (last primary sample 1, series stale) while
    # its Collector stays alive: the Collector half of the suppression.
    out += scenario(
        "S5 the leader's Patroni dies with its Collector alive: PatroniNoWritablePrimary and PatroniTargetAbsent",
        {
            1: {"prim": [(1, 20), ("_", n - 20)], "col": alive, "pat": [(1, 20), (0, n - 20)]},
            2: {"prim": zeros, "col": alive},
            3: {"prim": zeros, "col": alive},
        },
        [
            ([240], {}),
            (late, {"PatroniNoWritablePrimary": [no_primary()],
                    "PatroniTargetAbsent": [patroni_absent(1)]}),
        ],
    )
    # S7: the leader's Collector dies, pgha-2 is promoted at 7m30s, then pgha-2's
    # Patroni dies with its Collector alive: nobody is primary any more.
    leader_gone = {"prim": [(1, 20), ("_", n - 20)], "col": [(1, 20), ("_", n - 20)]}
    out += scenario(
        "S7 leader Collector dead, pgha-2 promoted, then pgha-2's Patroni dies: PatroniNoWritablePrimary fires",
        {
            1: leader_gone,
            2: {"prim": [(0, 30), (1, 30), ("_", 60)], "col": alive,
                "pat": [(1, 60), (0, 60)]},
            3: {"prim": zeros, "col": alive},
        },
        [
            ([600, 750], {"CollectorAbsent": [c1]}),
            ([1500, 1800], {"CollectorAbsent": [c1], "PatroniNoWritablePrimary": [no_primary()],
                            "PatroniTargetAbsent": [patroni_absent(2)]}),
        ],
    )
    # S2: the leader's Collector dies, pgha-2 is promoted at 7m30s and demoted
    # at 15m, everything alive: nobody is primary.
    out += scenario(
        "S2 leader Collector dead, pgha-2 promoted then demoted: PatroniNoWritablePrimary fires",
        {
            1: leader_gone,
            2: {"prim": [(0, 30), (1, 30), (0, 60)], "col": alive},
            3: {"prim": zeros, "col": alive},
        },
        [
            ([600, 750], {"CollectorAbsent": [c1]}),
            (
                [1200, 1500, 1800],
                {"CollectorAbsent": [c1], "PatroniNoWritablePrimary": [no_primary()]},
            ),
        ],
    )
    # S1: switchover pgha-1 -> pgha-2 at 5m, then pgha-2's Collector stops at
    # 15m: the most recent primary is the dead one, so quiet but its CollectorAbsent.
    gone_at_15m = {"prim": [(0, 20), (1, 40), ("_", 60)], "col": [(1, 60), ("_", 60)]}
    out += scenario(
        "S1 switchover, then the new leader's Collector stops: only its CollectorAbsent",
        {
            1: {"prim": [(1, 20), (0, n - 20)], "col": alive},
            2: gone_at_15m,
            3: {"prim": zeros, "col": alive},
        },
        [
            ([300, 600, 800], {}),
            ([1200, 1500, 1800], {"CollectorAbsent": [c2]}),
        ],
    )
    # S1b: after the switchover the old leader's Collector dies as a replica
    # (10m), then the new leader's Patroni dies with its Collector alive (15m).
    out += scenario(
        "S1b old leader's Collector dies as replica, then the new leader's Patroni dies: PatroniNoWritablePrimary fires",
        {
            1: {"prim": [(1, 20), (0, 20), ("_", 80)], "col": [(1, 40), ("_", 80)]},
            2: {"prim": [(0, 20), (1, 40), ("_", 60)], "col": alive,
                "pat": [(1, 60), (0, 60)]},
            3: {"prim": zeros, "col": alive},
        },
        [
            ([1500, 1800], {"CollectorAbsent": [c1], "PatroniNoWritablePrimary": [no_primary()],
                            "PatroniTargetAbsent": [patroni_absent(2)]}),
        ],
    )
    return out


def build():
    c1 = collector_alert("pgha-1")
    c2 = collector_alert("pgha-2")
    c3 = collector_alert("pgha-3")
    gw = collector_alert("gateway")
    later = [300, 360, 420]
    out = HEADER.format(rule_files="\n".join(f"  - {path}" for path in RULE_FILES))
    out += case(
        "one node Collector stops, its data outliving its last self-metric by 30 s: only its CollectorAbsent",
        input_series(coll_stop=(2,), lag=2), {"CollectorAbsent": [c2]})
    out += case(
        "the gateway stops, all four Collectors go silent together: only CollectorAbsent for the gateway",
        input_series(gw_stop=True, lag=1), {"CollectorAbsent": [gw]})
    out += case(
        "two node Collectors stop: two CollectorAbsent, no EtcdInsufficientMembers (unknown is not lost)",
        input_series(coll_stop=(1, 3), lag=2), {"CollectorAbsent": [c1, c3]})
    out += case(
        "a node Collector alive and its PostgreSQL heartbeat gone: PostgresTargetAbsent for that node only",
        input_series(hb_stop=(2,)), {"PostgresTargetAbsent": [postgres_absent(2)]})
    out += case(
        "all Collectors alive and two etcd scrapes failing: EtcdInsufficientMembers and both members named",
        input_series(etcd_fail=(2, 3)),
        {
            "EtcdInsufficientMembers": [insufficient(1)],
            "EtcdMemberAbsent": [etcd_absent(2), etcd_absent(3)],
        },
    )
    out += case(
        "one Collector stopped and a second member failing its etcd scrape: 2 of 3 count, no quorum alert",
        input_series(coll_stop=(2,), etcd_fail=(3,), lag=1),
        {"CollectorAbsent": [c2], "EtcdMemberAbsent": [etcd_absent(3)]}, later)
    out += case(
        "one Collector stopped and both other members failing their etcd scrape: only 1 counts, quorum alert fires",
        input_series(coll_stop=(2,), etcd_fail=(1, 3), lag=1),
        {
            "CollectorAbsent": [c2],
            "EtcdInsufficientMembers": [insufficient(1)],
            "EtcdMemberAbsent": [etcd_absent(1), etcd_absent(3)],
        },
        later,
    )
    # The gate is per Collector: another node's alerts still fire while node 2's
    # Collector is stopped.
    after_stop = [270, 300, 360, 420]
    # patroni_primary of a stopped leader leaves the 5 m lookback about 5 m
    # after its last sample; without the suppression the replicas alone would
    # then sum to 0 and fire after for: 90s, so the leader's case runs to 18m30s.
    long_run = [150 + 30 * i for i in range(33)]
    out += case(
        "node 2 Collector stopped and node 1 Patroni scrape failing with its heartbeat present: "
        "PatroniTargetAbsent for pgha-1 and CollectorAbsent for otelcol-pgha-2",
        input_series(coll_stop=(2,), patroni_fail=(1,), lag=1),
        {"CollectorAbsent": [c2], "PatroniTargetAbsent": [patroni_absent(1)]}, after_stop)
    out += case(
        "node 2 Collector stopped and node 3 etcd scrape failing: "
        "EtcdMemberAbsent for pgha-3 and CollectorAbsent for otelcol-pgha-2",
        input_series(coll_stop=(2,), etcd_fail=(3,), lag=1),
        {"CollectorAbsent": [c2], "EtcdMemberAbsent": [etcd_absent(3)]}, after_stop)
    out += case(
        "node 2 Collector stopped and node 1 PostgreSQL heartbeat gone: "
        "PostgresTargetAbsent for pgha-1 and CollectorAbsent for otelcol-pgha-2",
        input_series(coll_stop=(2,), hb_stop=(1,), lag=1),
        {"CollectorAbsent": [c2], "PostgresTargetAbsent": [postgres_absent(1)]}, after_stop)
    out += case(
        "the leader node's Collector stops: only its CollectorAbsent, no PatroniNoWritablePrimary "
        "when its patroni_primary goes stale",
        input_series(coll_stop=(1,), leader=1, lag=1, samples=80),
        {"CollectorAbsent": [c1]},
        long_run,
    )
    out += case(
        "a replica's Collector stops while no member reports primary: PatroniNoWritablePrimary "
        "and CollectorAbsent for the replica",
        input_series(coll_stop=(2,), leader=0, lag=1),
        {"CollectorAbsent": [c2], "PatroniNoWritablePrimary": [no_primary()]},
        later,
    )
    out += case(
        "all Collectors alive and no member reports primary: PatroniNoWritablePrimary",
        input_series(leader=0),
        {"PatroniNoWritablePrimary": [no_primary()]},
        later,
    )
    out += scenarios(c1, c2)
    return out.rstrip("\n") + "\n"


if __name__ == "__main__":
    text = build()
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
