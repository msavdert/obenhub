#!/usr/bin/env bash
# Scenario leader-killed: freeze Patroni on the current leader and let the hardware watchdog reset the VM. Replaces the stage 3 version (docker kill of the leader container, lab/stage3/scenarios/leader-killed.sh): there PostgreSQL died with its container, here it does not. On the leader, `systemctl show -p MainPID patroni` gives the Patroni main process and `kill -STOP` freezes only that process. `systemctl kill` is not used: it signals every process in the unit's cgroup, which includes the PostgreSQL processes Patroni started, so PostgreSQL would stop too and the fault would be "PostgreSQL killed" instead. With only Patroni frozen, PostgreSQL keeps running as primary and keeps taking writes, Patroni no longer pings /dev/watchdog (watchdog mode required, patroni.yml.tmpl; ttl 30, loop_wait 10, retry_timeout 10, safety_margin 5, so the watchdog timeout Patroni sets is expected to be about ttl - safety_margin = 25 s; the device facts are recorded below, nothing here assumes the value) and the watchdog is expected to hard-reset the VM. Approved by the owner. The VM is reset only through this scenario; nothing else is rebooted or touched.
# Manual run, 2026-11-09 (logs lost, so a hypothesis about the next run, not a result): the reset came about 20 s after the freeze, the old leader kept the leader key after the reboot (timeline 1 to 2), the write outage was about 16 s, 126 of 126 acknowledged rows were kept and the replicas never promoted. Two outcomes are legitimate and recorded as "outcome", neither fails the run: A, the old leader comes back and is leader again (the leader key survived the reset, or it won the race on return); B, a replica takes over (the key expired while the old leader was down) and the old leader rejoins as a replica, with pg_rewind if its timeline diverged.
# Writer: one INSERT per transaction, one row at a time, id from a counter kept in this shell, from this box through a libpq multi-host connection to all three nodes with target_session_attrs=read-write, so writes follow whichever node is primary. A row counts as acknowledged only when psql printed "INSERT 0 1" (commit returned). Acknowledged ids are logged on the box (a temp dir, deleted at the end; ids only). Authentication: the role app (owner of database app, no superuser) with APP_PASSWORD from lab/pgha/.env (gitignored, generated by scripts/gen-env.sh), over hostssl (pg_hba: hostssl all all SUBNET scram-sha-256; the superuser is allowed only from the members' own addresses, so the box cannot use it). The password is passed to the writer's psql through the PGPASSWORD environment variable of that subshell only; it is never printed, logged or written to a file, and the results line carries ids and counts only. The table obenhub_fault.leader_killed_writes is created in inject() as postgres on the leader's socket (schema and table owned by app; the app connection is checked with one insert, id 0) and dropped (schema CASCADE, as postgres on the leader's socket) at the end of revert().
# After the cluster is healthy again the writer is stopped and every acknowledged id is looked up on the leader. Outcome A: PostgreSQL on the old leader commits with a local fsync (assumption: fsync and synchronous_commit are at their defaults in patroni.yml.tmpl, not re-read for this scenario) and crash recovery replays the WAL, so a missing acknowledged row FAILS the run. Outcome B: replication is asynchronous, so the last acknowledged rows may not have reached the replica that took over; missing rows are evidence only (writer_missing in the results), the run does not fail on them. Everything else asserted: the old leader's boot id changes within 120 s after the freeze (otherwise Patroni is continued, the run fails with "watchdog did not reset the leader within 120 s" and the revert runs); no other node reboots; the poller never sees two writable nodes (dual primary); the cluster is healthy again within 300 s; the alerts below.
# Poller as in network-partition.sh (poll_node in lib.sh), POLL_AFTER set to the freeze epoch so poll_summary also reports the longest interval without a writable sample from any node that ends after the freeze, and the node writable at its end (the old leader itself in outcome A). seconds_without_writable_primary_poller is that interval; seconds_without_writable_primary_writer is the longest gap between two acknowledged writes (writer view, includes the writer's own retry delay).
# Evidence only (EXTRA_JSON, built once in finalize, which revert runs on every path): old and new leader, outcome, timelines, freeze time and epoch, Patroni's last journal line before the reset (VictoriaLogs, syslog.identifier patroni, looked up from 5 minutes before the freeze; the last line is from before the freeze in practice, since a frozen process logs nothing. Run 1 searched only after the freeze and found none), the new boot's first kernel line and the seconds from the freeze to it, watchdog identity, timeout and state of the old leader before the fault and the kernel driver (the loaded module whose name matches wdt, dog, esb or iTCO in /proc/modules; the sysfs node has no device/driver link), poller summary, writer counts, pg_rewind ran, boot-id results.
# shellcheck disable=SC1091,SC2034
set -uo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

# EXPECT is set in inject() once the old leader is known.
# - PatroniFailoverHappened: the highest timeline rose (lab/packs/patroni/rules.yml). The 2026-11-09 manual run saw 1 to 2 although the old leader kept the key (a restart after crash recovery or a new promotion; HYPOTHESIS, not confirmed from a log). If the timeline does not rise in outcome A, this expectation fails and that is a finding.
# - HostRebooted:<old leader>: system.uptime < 300 on the old leader's host (lab/packs/host/rules.yml), whatever happens to leadership afterwards.
# Not expected: PatroniNoWritablePrimary (for 90s; the write outage seen was about 16 s), the target-absent alerts and CollectorAbsent (windows of 1 to 2 m outlast a reset; same reasoning as network-partition.sh), the etcd alerts (etcd on the old leader's node stops with the VM; two of three members keep quorum, EtcdMemberAbsent has the same window).
# Allowed, not expected (decided from the rule files, to be confirmed or removed by the first runs):
# - PhysicalSlotInactive:<new leader>, outcome B only: the new leader keeps a slot for the old leader that is inactive until the old leader has rejoined (added in finalize).
# - StandbyNotStreaming:<node> for the two other nodes, only outcome A: while the old leader is down both replicas stand without a WAL sender; the rule needs for 1m and another writable node in the lab (postgresql pack), which a long enough boot and crash recovery may satisfy. NOT allowed yet: added in finalize only when a smoke run shows it.
EXPECT=()
ALLOW=()
OLD="" TL0="" FREEZE_PID="" FREEZE_EPOCH="" FREEZE_T=""
OUTCOME="" WD_JSON=null REB_SEEN="" WR_STOP=""
EXTRA_JSON=null
FINALIZED=0
declare -A BOOT0=()
WR_DIR="" WR_PID=""
WTABLE=obenhub_fault.leader_killed_writes
ENV_FILE="$LAB_DIR/.env"

# conninfo for all three nodes, no password in it
conninfo() {
  local ips="" n
  for n in "${NODES[@]}"; do ips="$ips${ips:+,}$(node_ip "$n")"; done
  printf 'host=%s port=5432 dbname=app user=app sslmode=require target_session_attrs=read-write connect_timeout=2' "$ips"
}
# app_psql ARGS...: psql from this box as role app against whichever node is primary. The
# password is read from .env into the environment of this one call.
app_psql() {
  local pw
  pw=$(sed -n 's/^APP_PASSWORD=//p' "$ENV_FILE" | head -n1)
  [ -n "$pw" ] || return 2
  PGPASSWORD=$pw timeout 8 psql "$(conninfo)" -X -v ON_ERROR_STOP=1 -At "$@"
}
# writer PARENT: ids 1, 2, ... one INSERT each; acknowledged ids go to $WR_DIR/acked as "epoch id"
writer() {
  local parent=$1 i=0 pw r
  pw=$(sed -n 's/^APP_PASSWORD=//p' "$ENV_FILE" | head -n1)
  [ -n "$pw" ] || exit 2
  while kill -0 "$parent" 2>/dev/null; do
    i=$((i + 1))
    # exec: the substitution's subshell becomes timeout, so stop_writer's pkill -P reaches
    # it and timeout passes the TERM on to psql
    r=$(PGPASSWORD=$pw exec timeout 8 psql "$(conninfo)" -X -v ON_ERROR_STOP=1 -At -c "INSERT INTO $WTABLE (id) VALUES ($i)" 2>/dev/null) || r=""
    # a failed or unanswered insert is not acknowledged; its id is not reused
    if [ "$r" = "INSERT 0 1" ]; then echo "$(date +%s.%N) $i" >>"$WR_DIR/acked"; else sleep 0.3; fi
    sleep 0.1
  done
}
start_writer() {
  WR_DIR=$(mktemp -d)
  : >"$WR_DIR/acked"
  writer "$$" 2>/dev/null &
  WR_PID=$!
}
stop_writer() {
  [ -z "$WR_PID" ] && return 0
  # the in-flight psql too (via its timeout), so no insert lands after the count
  pkill -P "$WR_PID" 2>/dev/null; kill "$WR_PID" 2>/dev/null; wait "$WR_PID" 2>/dev/null
  WR_STOP=$(date +%s.%N)
  WR_PID=""
}

# watchdog_facts NODE: JSON of what the kernel says about /dev/watchdog on NODE
# shellcheck disable=SC2016
watchdog_facts() {
  rn "$1" sh -c 'd=/sys/class/watchdog/watchdog0
    [ -d $d ] || exit 0
    rd() { [ -r $d/$1 ] && cat $d/$1 || echo; }
    drv=$(grep -E "wdt|dog|esb|iTCO" /proc/modules | cut -d" " -f1 | paste -sd, -)
    printf "%s\n%s\n%s\n%s\n%s\n" "$(rd identity)" "$(rd timeout)" "$(rd state)" "$(rd nowayout)" "$drv"' \
    | jq -R -s -c 'split("\n") | {identity: .[0], timeout_seconds: (.[1]|tonumber? // null), state: .[2], nowayout: .[3], driver: .[4]} | with_entries(select(.value != "" and .value != null))'
}

reset_seen() { local b; b=$(boot_id "$OLD" 2>/dev/null) && [ -n "$b" ] && [ "$b" != "${BOOT0[$OLD]}" ]; }

# continue_patroni: SIGCONT the frozen process when it still exists on the same boot. A pid
# can be reused after a reset, so the boot id and the process name are checked first.
# shellcheck disable=SC2016
continue_patroni() {
  [ -n "$FREEZE_PID" ] || return 0
  # unreadable even after retries: nothing to do from here; a frozen Patroni stops
  # feeding the watchdog, which resets the VM anyway, and cluster_healthy decides
  local b; b=$(boot_id_retry "$OLD" 2>/dev/null) || { log "boot id of $OLD unreadable; not sending SIGCONT"; return 0; }
  [ "$b" = "${BOOT0[$OLD]}" ] || return 0
  rn "$OLD" sh -c 'p=$1; if ps -o stat=,args= -p "$p" | grep -q "^T.*patroni"; then kill -CONT "$p"; fi; true' sh "$FREEZE_PID"
}

inject() {
  local n b
  OLD=$(leader_name)
  [ -n "$OLD" ] || return 1
  TL0=$(timeline)
  for n in "${NODES[@]}"; do b=$(boot_id_retry "$n") && BOOT0[$n]=$b || return 1; done
  WD_JSON=$(watchdog_facts "$OLD") || WD_JSON=null
  [ -n "$WD_JSON" ] || WD_JSON=null
  log "leader $OLD, timeline $TL0, watchdog $WD_JSON"
  # the table: dropped first, a left-over from a killed run must not count
  psql_n "$OLD" -d app -c "DROP SCHEMA IF EXISTS obenhub_fault CASCADE; CREATE SCHEMA obenhub_fault AUTHORIZATION app; CREATE TABLE $WTABLE (id int PRIMARY KEY, ts timestamptz NOT NULL DEFAULT now()); ALTER TABLE $WTABLE OWNER TO app" >/dev/null || return 1
  app_psql -c "INSERT INTO $WTABLE (id) VALUES (0)" >/dev/null || { FAILS+=("writer connection as role app failed (APP_PASSWORD in $ENV_FILE, hostssl from this box)"); return 1; }
  start_poll
  start_writer
  sleep 5
  [ -s "$WR_DIR/acked" ] || { FAILS+=("writer acknowledged no row in 5 s before the fault"); return 1; }
  FREEZE_PID=$(rn "$OLD" systemctl show -p MainPID --value patroni) || return 1
  [[ $FREEZE_PID =~ ^[0-9]+$ ]] && [ "$FREEZE_PID" -gt 1 ] || { FAILS+=("no Patroni MainPID on $OLD ($FREEZE_PID)"); FREEZE_PID=""; return 1; }
  POLL_AFTER=$(date +%s.%N)
  FREEZE_T=$(now_ts)
  FREEZE_EPOCH=$POLL_AFTER
  log "freezing Patroni (pid $FREEZE_PID) on $OLD; PostgreSQL keeps running"
  # FREEZE_PID is kept on failure: the signal may have been delivered before ssh failed
  rn "$OLD" kill -STOP "$FREEZE_PID" || { FAILS+=("kill -STOP failed on $OLD"); return 1; }
  if ! wait_until 120 "old leader's boot id changed (watchdog reset)" reset_seen; then
    continue_patroni
    FAILS+=("watchdog did not reset the leader within 120 s")
    return 1
  fi
  REB_SEEN=1
  EXPECT=("PatroniFailoverHappened:" "HostRebooted:$OLD")
  log "old leader $OLD was reset; expecting ${EXPECT[*]}"
}

# first VictoriaLogs record of NODE matching FILTER after SINCE: prints "_time"
first_line_time() { vl "host.name:=$1 _time:>$2 $3 | sort by (_time) | limit 1 | fields _time" | jq -r '._time // empty' | head -n1; }
have_boot_line() { [ -n "$(first_line_time "$OLD" "$FREEZE_T" '"Linux version"')" ]; }

finalize() {
  [ "$FINALIZED" = 0 ] || return 0
  FINALIZED=1
  stop_poll
  stop_writer
  local nl="" n b summary=null dual resumed lastw gap reb=null othreb=false unknown=() tl1 rw rewinds=null since
  local boot_t="" boot_s=null plast="" plast_t="" plast_msg="" acked=0 missing=null miss_ids="" first_t last_t wgap=null
  if [ -n "$POLL_DIR" ]; then
    summary=$(poll_summary) || summary=null
    [ -n "$summary" ] || summary=null
    rm -rf "$POLL_DIR"; POLL_DIR=""
  fi
  nl=$(leader_name 2>/dev/null) || nl=""
  # FAULTED: the freeze was sent; before that, poller and writer checks would only add noise
  local faulted=""
  [ -n "$FREEZE_EPOCH" ] && faulted=1
  if [ -n "$OLD" ]; then
    if [ "$REB_SEEN" != 1 ]; then OUTCOME=""
    elif [ -z "$nl" ]; then OUTCOME=unknown
    elif [ "$nl" = "$OLD" ]; then OUTCOME=A
    else OUTCOME=B; ALLOW+=("PhysicalSlotInactive:$nl"); fi
  fi
  # poller checks
  dual=$(jq -r '.dual_samples // empty' <<<"$summary" 2>/dev/null)
  if [ "$(jq -r '.samples // 0' <<<"$summary" 2>/dev/null)" -eq 0 ] 2>/dev/null || [ -z "$dual" ]; then
    [ -n "$faulted" ] && FAILS+=("poller produced no samples"); summary=null
  else
    [ "$dual" = 0 ] || FAILS+=("two nodes writable at once in $dual samples: dual primary")
    resumed=$(jq -r '.resumed_first_writable // empty' <<<"$summary")
    [ -n "$resumed" ] || [ "$REB_SEEN" != 1 ] || FAILS+=("poller never saw a writable node after the old leader stopped being writable")
  fi
  # boot ids
  if [ -n "$OLD" ]; then
    for n in "${NODES[@]}"; do
      b=$(boot_id_retry "$n") || { unknown+=("$n"); continue; }
      if [ "$b" != "${BOOT0[$n]}" ]; then
        if [ "$n" = "$OLD" ]; then reb=true; else othreb=true; FAILS+=("$n rebooted"); fi
      elif [ "$n" = "$OLD" ]; then reb=false; fi
    done
    [ "${#unknown[@]}" -eq 0 ] || FAILS+=("boot id unreadable on: ${unknown[*]}")
  fi
  tl1=$(timeline 2>/dev/null) || tl1=""
  # writer: acknowledged ids against the leader's table
  if [ -n "$WR_DIR" ] && [ -f "$WR_DIR/acked" ] && [ -n "$nl" ]; then
    acked=$(wc -l <"$WR_DIR/acked")
    if psql_n "$nl" -d app -c "SELECT id FROM $WTABLE" 2>/dev/null | LC_ALL=C sort >"$WR_DIR/have" && [ -s "$WR_DIR/have" ]; then
      awk '{print $2}' "$WR_DIR/acked" | LC_ALL=C sort >"$WR_DIR/want"
      miss_ids=$(LC_ALL=C comm -23 "$WR_DIR/want" "$WR_DIR/have" | sort -n | head -n 200 | paste -sd, -)
      missing=$(LC_ALL=C comm -23 "$WR_DIR/want" "$WR_DIR/have" | wc -l)
      if [ "$missing" -gt 0 ] && [ "$OUTCOME" = A ]; then
        FAILS+=("outcome A: $missing acknowledged rows missing on the leader $nl (of $acked); ids: ${miss_ids:0:200}")
      fi
    else
      FAILS+=("cannot read $WTABLE on the leader ${nl:-?}")
    fi
    # longest gap between two acknowledged writes, in seconds, within [freeze - 5 s, end]
    # the writer's stop time closes the last interval, so writes that never resume show as a gap
    wgap=$(awk -v f="${FREEZE_EPOCH:-0}" -v e="${WR_STOP:-0}" '{ if (p && $1 >= f - 5 && $1 - p > m) m = $1 - p; p = $1 } END { if (p && e > p && e - p > m) m = e - p; printf "%.1f", m }' "$WR_DIR/acked")
  else
    [ -n "$faulted" ] && FAILS+=("writer result not available (no leader or no acknowledged ids)")
  fi
  rm -rf "$WR_DIR"; WR_DIR=""
  # logs: the new boot's first kernel line, Patroni's last line before it
  if [ -n "$OLD" ] && [ "$reb" = true ]; then
    wait_until 60 "new boot's kernel line in VictoriaLogs" have_boot_line
    boot_t=$(first_line_time "$OLD" "$FREEZE_T" '"Linux version"' || true)
    if [ -n "$boot_t" ]; then
      boot_s=$(secs "$FREEZE_T" "$boot_t")
      plast=$(vl "host.name:=$OLD syslog.identifier:=patroni _time:>$(date -u -d "@$((${FREEZE_EPOCH%.*} - 300))" +%Y-%m-%dT%H:%M:%SZ) _time:<$boot_t | sort by (_time desc) | limit 1 | fields _time,_msg" 2>/dev/null | head -n1)
      plast_t=$(jq -r '._time // empty' <<<"$plast" 2>/dev/null)
      plast_msg=$(jq -r '._msg // empty' <<<"$plast" 2>/dev/null)
    fi
  fi
  rewinds=null
  if [ -n "$OLD" ] && [ -n "$FREEZE_EPOCH" ]; then
    since=${FREEZE_EPOCH%.*}
    rw=$(rn "$OLD" sh -c "journalctl -u patroni --since @$since --no-pager | grep -ci 'running pg_rewind' || true" 2>/dev/null) || rw=""
    [[ $rw =~ ^[0-9]+$ ]] && rewinds=$rw
  fi
  gap=null
  [ -n "$FREEZE_EPOCH" ] && gap=$(primary_gap_seconds "${FREEZE_EPOCH%.*}" 2>/dev/null) || gap=null
  [ -n "$gap" ] || gap=null
  [ "$missing" = null ] || [[ $missing =~ ^[0-9]+$ ]] || missing=null
  EXTRA_JSON=$(jq -n -c --arg old "$OLD" --arg out "$OUTCOME" --arg nl "$nl" --argjson tl0 "${TL0:-0}" --argjson tl1 "${tl1:-0}" \
    --arg ft "$FREEZE_T" --arg fe "${FREEZE_EPOCH:-}" --arg pt "$plast_t" --arg pm "$plast_msg" --arg bt "$boot_t" --argjson bs "$boot_s" \
    --argjson wd "${WD_JSON:-null}" --argjson poll "$summary" --argjson acked "$acked" --argjson missing "${missing:-null}" --arg mids "$miss_ids" \
    --argjson wgap "${wgap:-null}" --argjson rewinds "$rewinds" --argjson reb "$reb" --argjson othreb "$othreb" --argjson gap "$gap" '
    def nz: if . == "" then null else . end;
    {old_leader: ($old|nz), outcome: ($out|nz), new_leader: ($nl|nz), timeline_before: $tl0, timeline_after: $tl1,
     freeze_time: ($ft|nz), freeze_epoch: ($fe|nz|if . then tonumber else . end),
     patroni_last_line_before_reset_time: ($pt|nz), patroni_last_line_before_reset: ($pm|nz),
     new_boot_first_kernel_line: ($bt|nz), seconds_freeze_to_new_boot_first_kernel_line: $bs,
     watchdog: $wd,
     poll_samples: $poll.samples, samples_with_two_writable: $poll.dual_samples, poll_nodes: $poll.nodes,
     old_leader_last_writable_before_gap_epoch: $poll.old_last_writable_before_that,
     old_leader_first_unwritable_epoch: $poll.old_first_unwritable_after,
     first_writable_after_gap_epoch: $poll.resumed_first_writable, first_writable_after_gap_node: $poll.resumed_node,
     seconds_without_writable_primary_poller: (if $poll != null and $poll.old_last_writable_before_that != null and $poll.resumed_first_writable != null then ($poll.resumed_first_writable - $poll.old_last_writable_before_that) else null end),
     seconds_without_writable_primary_writer: $wgap,
     primary_gap_seconds: $gap,
     writer_acked: $acked, writer_missing: $missing, writer_missing_ids_first_200: ($mids|nz),
     pg_rewind_ran: (if $rewinds == null then null else $rewinds > 0 end), pg_rewind_journal_lines: $rewinds,
     old_leader_rebooted: $reb, other_nodes_rebooted: $othreb}')
  log "extra: $EXTRA_JSON"
}

revert() {
  local rc=0 l
  if [ -n "$OLD" ]; then
    continue_patroni || rc=1
    wait_until 300 "cluster healthy" cluster_healthy || rc=1
  fi
  finalize
  if [ -n "$OLD" ]; then
    l=$(leader_name 2>/dev/null)
    if [ -n "$l" ]; then psql_n "$l" -d app -c "DROP SCHEMA IF EXISTS obenhub_fault CASCADE" >/dev/null || rc=1; else rc=1; fi
  fi
  return "$rc"
}
run_scenario leader-killed
